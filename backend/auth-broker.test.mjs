import assert from 'node:assert/strict';
import { after, test } from 'node:test';
import { mkdtempSync, rmSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
	exportJWK,
	generateKeyPair,
	SignJWT,
} from 'jose';
import { createAuthBroker, getConfig } from './auth-broker.mjs';

const temporaryDirectory = mkdtempSync(join(tmpdir(), 'ide-logbutton-auth-'));
const databasePath = join(temporaryDirectory, 'accounts.sqlite');
const githubHost = 'ghe.example.com';
const config = {
	port: 0,
	publicBaseUrl: 'https://broker.example.test',
	callbackUri: 'vscode://moonpy-a11y.github-sign-in/auth-callback',
	databasePath,
	githubHost,
	githubClientId: 'github-client',
	githubClientSecret: 'github-secret',
	googleClientId: 'google-client',
	googleClientSecret: 'google-secret',
	appleClientId: 'apple-client',
	appleTeamId: 'apple-team',
	appleKeyId: 'apple-key',
	applePrivateKey: '',
};
const githubKeyPair = await generateKeyPair('RS256');
const appleKeyPair = await generateKeyPair('ES256', { extractable: true });
config.applePrivateKey = await importPKCS8ForTest(appleKeyPair.privateKey);

const googleJwks = {
	keys: [{ ...(await exportJWK(githubKeyPair.publicKey)), kid: 'google-test-key', use: 'sig', alg: 'RS256' }],
};
const appleJwks = {
	keys: [{ ...(await exportJWK(githubKeyPair.publicKey)), kid: 'apple-test-key', use: 'sig', alg: 'RS256' }],
};
const providerTokens = new Map();
let githubToken;

const fetchMock = async (input, init = {}) => {
	const url = new URL(input);
	if (url.pathname === '/login/oauth/access_token' && url.hostname === githubHost) {
		const body = JSON.parse(init.body);
		assert.equal(body.client_id, config.githubClientId);
		assert.equal(body.client_secret, config.githubClientSecret);
		githubToken = body.code === 'github-other' ? 'github-token-other' : 'github-token';
		return Response.json({ access_token: githubToken });
	}
	if (url.pathname === '/api/v3/user' && url.hostname === githubHost) {
		assert.match(init.headers.authorization, /^Bearer github-token/);
		return Response.json(githubToken === 'github-token-other'
			? { id: 456, login: 'other-user' }
			: { id: 123, login: 'octocat' });
	}
	if (url.pathname === '/token' && url.hostname === 'oauth2.googleapis.com') {
		const body = new URLSearchParams(init.body);
		assert.equal(body.get('client_secret'), config.googleClientSecret);
		return Response.json({ id_token: providerTokens.get(body.get('code')) });
	}
	if (url.pathname === '/auth/token' && url.hostname === 'appleid.apple.com') {
		const body = new URLSearchParams(init.body);
		assert.ok(body.get('client_secret'), 'Apple client secret is generated by the broker');
		return Response.json({ id_token: providerTokens.get(body.get('code')) });
	}
	if (url.pathname === '/oauth2/v3/certs' && url.hostname === 'www.googleapis.com') {
		return Response.json(googleJwks);
	}
	if (url.pathname === '/auth/keys' && url.hostname === 'appleid.apple.com') {
		return Response.json(appleJwks);
	}
	throw new Error(`Unexpected external request: ${url.href}`);
};

const server = createAuthBroker(config, { fetchImpl: fetchMock, databasePath });
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const address = server.address();
assert.ok(address && typeof address === 'object');
const brokerUrl = `http://127.0.0.1:${address.port}`;

after(async () => {
	await new Promise((resolve, reject) => server.close(error => error ? reject(error) : resolve()));
	rmSync(temporaryDirectory, { recursive: true, force: true });
});

test('requires a valid host, public URL, and all provider credentials', () => {
	assert.throws(() => getConfig({}), /PUBLIC_BASE_URL is required/);
	assert.throws(() => getConfig({
		PUBLIC_BASE_URL: 'http://example.test',
	}), /must use HTTPS/);
	assert.throws(() => getConfig({
		PUBLIC_BASE_URL: 'https://broker.example.test',
		GITHUB_HOST: 'https://github.com',
	}), /hostname without a scheme/);
	assert.throws(() => getConfig({
		PUBLIC_BASE_URL: 'https://broker.example.test',
	}), /GITHUB_CLIENT_ID is required/);
});

test('links Google and Apple identities to the verified GitHub Enterprise account', async () => {
	const googleClientState = 'g'.repeat(43);
	const appleClientState = 'a'.repeat(43);
	const google = await beginFlow('google', googleClientState);
	assert.equal(new URL(google.authorizationUrl).hostname, githubHost);
	assert.equal(new URL(google.authorizationUrl).pathname, '/login/oauth/authorize');

	const googleCallback = await completeGitHub(google, 'github-same');
	assert.equal(googleCallback.status, 302, await googleCallback.clone().text());
	assert.equal(new URL(googleCallback.headers.get('location')).hostname, 'accounts.google.com');
	const googleProviderUrl = new URL(googleCallback.headers.get('location'));
	providerTokens.set('google-code', await makeProviderIdToken({
		issuer: 'https://accounts.google.com',
		audience: config.googleClientId,
		subject: 'google-subject',
		nonce: googleProviderUrl.searchParams.get('nonce'),
		kid: 'google-test-key',
	}));
	const googleReturn = await completeProvider('google', googleProviderUrl.searchParams.get('state'), 'google-code');
	const googleResult = await redeem(googleReturn, googleClientState);
	assert.deepEqual(googleResult, {
		provider: 'google',
		githubHost,
		githubLogin: 'octocat',
		providers: ['google'],
	});

	const apple = await beginFlow('apple', appleClientState);
	const appleCallback = await completeGitHub(apple, 'github-same');
	assert.equal(new URL(appleCallback.headers.get('location')).hostname, 'appleid.apple.com');
	const appleProviderUrl = new URL(appleCallback.headers.get('location'));
	assert.equal(appleProviderUrl.searchParams.get('response_mode'), 'form_post');
	providerTokens.set('apple-code', await makeProviderIdToken({
		issuer: 'https://appleid.apple.com',
		audience: config.appleClientId,
		subject: 'apple-subject',
		nonce: appleProviderUrl.searchParams.get('nonce'),
		kid: 'apple-test-key',
	}));
	const appleReturn = await completeProvider('apple', appleProviderUrl.searchParams.get('state'), 'apple-code', true);
	const appleResult = await redeem(appleReturn, appleClientState);
	assert.deepEqual(appleResult, {
		provider: 'apple',
		githubHost,
		githubLogin: 'octocat',
		providers: ['apple', 'google'],
	});
	assert.equal(statSync(databasePath).mode & 0o777, 0o600);
});

test('rejects linking one provider identity to a different GitHub account', async () => {
	const clientState = 'c'.repeat(43);
	const flow = await beginFlow('google', clientState);
	const githubCallback = await completeGitHub(flow, 'github-other');
	assert.equal(githubCallback.status, 302, await githubCallback.clone().text());
	const providerUrl = new URL(githubCallback.headers.get('location'));
	providerTokens.set('google-conflict-code', await makeProviderIdToken({
		issuer: 'https://accounts.google.com',
		audience: config.googleClientId,
		subject: 'google-subject',
		nonce: providerUrl.searchParams.get('nonce'),
		kid: 'google-test-key',
	}));
	const providerReturn = await completeProvider('google', providerUrl.searchParams.get('state'), 'google-conflict-code');
	const callback = new URL(providerReturn.headers.get('location'));
	assert.equal(callback.searchParams.get('error'), 'identity_already_linked');
	assert.equal(await fetch(`${brokerUrl}/auth/redeem`, {
		method: 'POST',
		headers: { 'content-type': 'application/json' },
		body: JSON.stringify({
			code: callback.searchParams.get('code'),
			client_state: clientState,
		}),
	}).then(response => response.status), 400);
});

test('rejects host mismatches, replayed codes, and incorrect client state', async () => {
	const clientState = 's'.repeat(43);
	const mismatch = await fetch(`${brokerUrl}/auth/start?provider=google&host=github.com&client_state=${clientState}`);
	assert.equal(mismatch.status, 400);
	assert.equal((await mismatch.json()).error, 'github_host_mismatch');

	const singleUseState = 'u'.repeat(43);
	const flow = await beginFlow('google', singleUseState);
	const githubCallback = await completeGitHub(flow, 'github-same');
	assert.equal(githubCallback.status, 302, await githubCallback.clone().text());
	const providerUrl = new URL(githubCallback.headers.get('location'));
	providerTokens.set('google-single-code', await makeProviderIdToken({
		issuer: 'https://accounts.google.com',
		audience: config.googleClientId,
		subject: 'another-google-subject',
		nonce: providerUrl.searchParams.get('nonce'),
		kid: 'google-test-key',
	}));
	const providerReturn = await completeProvider('google', providerUrl.searchParams.get('state'), 'google-single-code');
	const code = new URL(providerReturn.headers.get('location')).searchParams.get('code');

	const incorrectState = await redeemCode(code, 'w'.repeat(43));
	assert.equal(incorrectState.status, 400);
	const replay = await redeemCode(code, singleUseState);
	assert.equal(replay.status, 400);
});

async function beginFlow(provider, clientState) {
	const response = await fetch(`${brokerUrl}/auth/start?${new URLSearchParams({
		provider,
		host: githubHost,
		client_state: clientState,
	})}`);
	assert.equal(response.status, 200);
	return response.json();
}

async function completeGitHub(flow, code) {
	const url = new URL(flow.authorizationUrl);
	return fetch(`${brokerUrl}/oauth/github/callback?${new URLSearchParams({
		code,
		state: url.searchParams.get('state'),
	})}`, { redirect: 'manual' });
}

async function completeProvider(provider, state, code, formPost = false) {
	const route = `${brokerUrl}/oauth/${provider}/callback`;
	if (formPost) {
		return fetch(route, {
			method: 'POST',
			redirect: 'manual',
			headers: { 'content-type': 'application/x-www-form-urlencoded' },
			body: new URLSearchParams({ code, state }),
		});
	}
	return fetch(`${route}?${new URLSearchParams({ code, state })}`, { redirect: 'manual' });
}

async function redeem(result, clientState) {
	const response = await redeemCode(new URL(result.headers.get('location')).searchParams.get('code'), clientState);
	assert.equal(response.status, 200);
	return response.json();
}

async function redeemCode(code, clientState) {
	return fetch(`${brokerUrl}/auth/redeem`, {
		method: 'POST',
		headers: { 'content-type': 'application/json' },
		body: JSON.stringify({ code, client_state: clientState }),
	});
}

async function makeProviderIdToken({ issuer, audience, subject, nonce, kid }) {
	return new SignJWT({
		nonce,
		...(issuer === 'https://accounts.google.com' ? { email_verified: true } : {}),
	})
		.setProtectedHeader({ alg: 'RS256', kid })
		.setIssuer(issuer)
		.setAudience(audience)
		.setSubject(subject)
		.setIssuedAt()
		.setExpirationTime('5m')
		.sign(githubKeyPair.privateKey);
}

async function importPKCS8ForTest(key) {
	const { exportPKCS8 } = await import('jose');
	return exportPKCS8(key);
}
